#!/usr/bin/env python3
"""Layered map generator (Winning Combination, Stage 5).

The map is the primary surface: program -> components -> claims ->
evidence, rendered ONLY from generated data (the ledger, the matrix,
the evaluation). Every element carries its ledger claim ids. The
header carries the headline state: the headline claim's status,
claims by status, the evaluation counts, and the most recent claims
by date.

Generation is deterministic (no timestamps; the canonical ledger
hash is the provenance stamp), so --check can verify the committed
map byte-exactly, and the gate (tools/gate.py, G5) fails on drift.

  python3 tools/build_map.py           # write program-ledger/map.html
  python3 tools/build_map.py --check   # regenerate and diff; never write
"""

from __future__ import annotations

import argparse
import html
import importlib.util
import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
LEDGER_DIR = ROOT / "program-ledger"
sys.dont_write_bytecode = True  # check mode writes nothing, not even .pyc caches
if str(ROOT / "src") not in sys.path:
    sys.path.insert(0, str(ROOT / "src"))

_spec = importlib.util.spec_from_file_location("ledger_intake", LEDGER_DIR / "intake.py")
assert _spec is not None and _spec.loader is not None
intake = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(intake)

HEADLINE_CLAIM = "SKA-001"

CSS = """
body { font-family: system-ui, sans-serif; margin: 2rem auto;
  max-width: 72rem; padding: 0 1rem; color: #1a1a1a; }
header { border-bottom: 3px solid #1a1a1a; padding-bottom: 1rem;
  margin-bottom: 1.5rem; }
h1 { font-size: 1.6rem; margin: 0 0 .5rem; }
h2 { font-size: 1.2rem; margin-top: 2rem; }
table { border-collapse: collapse; width: 100%; margin: .5rem 0 1rem; }
th, td { border: 1px solid #ccc; padding: .35rem .5rem; text-align: left;
  vertical-align: top; font-size: .9rem; }
th { background: #f2f2f2; }
.status { font-weight: 600; }
.small { color: #555; font-size: .85rem; }
code { font-size: .82rem; }
""".strip()


def esc(value: Any) -> str:
    return html.escape(str(value), quote=True)


def build_map(ledger_dir: Path) -> str:
    claims = [
        json.loads(line)
        for line in (ledger_dir / "claims.jsonl").read_text(encoding="utf-8").splitlines()
        if line.strip()
    ]
    matrix = json.loads((ledger_dir / "matrix.json").read_text(encoding="utf-8"))
    evaluation = json.loads((ledger_dir / "evaluation.json").read_text(encoding="utf-8"))
    components = json.loads((ledger_dir / "components.json").read_text(encoding="utf-8"))
    ledger_sha = intake.ledger_sha256(ledger_dir / "claims.jsonl")
    verdicts = {v["id"]: v["verdict"] for v in evaluation["verdicts"]}
    by_id = {c["id"]: c for c in claims}
    headline = by_id.get(HEADLINE_CLAIM, {})
    recent = sorted(claims, key=lambda c: c["metadata"].get("date", ""), reverse=True)[:5]

    status_counts = matrix["counts"]["by_status"]
    status_line = ", ".join(f"{k}: {v}" for k, v in status_counts.items())
    eval_counts = evaluation["counts"]
    eval_line = ", ".join(f"{k}: {v}" for k, v in sorted(eval_counts.items()))

    parts: list[str] = [
        "<!DOCTYPE html>",
        '<html lang="en">',
        "<head>",
        '<meta charset="utf-8">',
        "<title>Spec-Kit AEE program map</title>",
        f"<style>{CSS}</style>",
        "</head>",
        "<body>",
        "<header>",
        "<h1>Spec-Kit AEE program map</h1>",
        f"<p>Headline claim <code>{HEADLINE_CLAIM}</code> status: "
        f"<span class='status'>{esc(headline.get('status', 'unknown'))}</span> "
        f"(evaluation: {esc(verdicts.get(HEADLINE_CLAIM, 'unknown'))})</p>",
        f"<p>Claims by status: {esc(status_line)}. Evaluation: {esc(eval_line)}.</p>",
        f"<p class='small'>Ledger sha256 {esc(ledger_sha)} · generated by "
        "tools/build_map.py from claims.jsonl + matrix.json + evaluation.json · "
        "do not hand-edit.</p>",
        "</header>",
        "<h2>Most recent claims</h2>",
        "<ul>",
    ]
    for claim in recent:
        parts.append(
            f"<li><code>{esc(claim['id'])}</code> ({esc(claim['metadata'].get('date', ''))}, "
            f"{esc(claim['status'])}) {esc(claim['text'])}</li>"
        )
    parts += ["</ul>", "<h2>Layer 1 — components</h2>", "<table>"]
    parts.append("<tr><th>component</th><th>claims</th><th>by status</th></tr>")
    for comp in components:
        cid = comp["id"]
        statuses = matrix["matrix"].get(cid, {})
        total = sum(len(v) for v in statuses.values())
        mix = ", ".join(f"{k}: {len(v)}" for k, v in sorted(statuses.items())) or "none"
        parts.append(
            f"<tr data-component='{esc(cid)}'><td>{esc(comp['name'])}</td>"
            f"<td>{total}</td><td>{esc(mix)}</td></tr>"
        )
    parts += ["</table>", "<h2>Layer 2 — claims</h2>", "<table>"]
    parts.append(
        "<tr><th>claim</th><th>status</th><th>evaluation</th><th>stage</th>"
        "<th>date</th><th>components</th><th>statement</th></tr>"
    )
    for claim in claims:
        cid = claim["id"]
        comps = ", ".join(claim["metadata"].get("components", []))
        parts.append(
            f"<tr data-claim-id='{esc(cid)}'><td><code>{esc(cid)}</code></td>"
            f"<td class='status'>{esc(claim['status'])}</td>"
            f"<td>{esc(verdicts.get(cid, ''))}</td>"
            f"<td>{esc(claim.get('stage', ''))}</td>"
            f"<td>{esc(claim['metadata'].get('date', ''))}</td>"
            f"<td>{esc(comps)}</td><td>{esc(claim['text'])}</td></tr>"
        )
    parts += ["</table>", "<h2>Layer 3 — evidence</h2>", "<table>"]
    parts.append(
        "<tr><th>claim</th><th>evidence ref</th><th>kind</th><th>direction</th><th>hash</th></tr>"
    )
    for claim in claims:
        for ev in claim.get("evidence", []):
            parts.append(
                f"<tr data-claim-id='{esc(claim['id'])}'><td><code>{esc(claim['id'])}</code></td>"
                f"<td>{esc(ev.get('ref', ''))}</td><td>{esc(ev.get('kind', ''))}</td>"
                f"<td>{esc(ev.get('direction', ''))}</td>"
                f"<td><code>{esc(ev.get('content_hash') or '')}</code></td></tr>"
            )
    parts += ["</table>", "</body>", "</html>"]
    return "\n".join(parts) + "\n"


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="diff instead of write")
    parser.add_argument("--ledger-dir", type=Path, default=LEDGER_DIR)
    args = parser.parse_args(argv)
    text = build_map(args.ledger_dir)
    target = args.ledger_dir / "map.html"
    if args.check:
        if not target.is_file() or target.read_bytes() != text.encode("utf-8"):
            print("MAP_CHECK DRIFT in: map.html")
            return 1
        print("MAP_CHECK OK byte-identical")
        return 0
    target.write_text(text, encoding="utf-8", newline="\n")
    print(f"MAP_WROTE map.html bytes={len(text.encode('utf-8'))}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
